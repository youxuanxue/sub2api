// Command gpt-image-sizes-ssot materializes Studio/Quickstart GPT Image size
// chips from the Go owner openAIImagesKnownSizeTable.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/Wei-Shaw/sub2api/internal/service"
)

func main() {
	outputPath := flag.String("output", "", "write the generated TypeScript artifact to this path")
	checkPath := flag.String("check", "", "fail when this file differs from the generated artifact")
	flag.Parse()

	if strings.TrimSpace(*outputPath) != "" && strings.TrimSpace(*checkPath) != "" {
		fatal("--output and --check are mutually exclusive")
	}
	payload := renderGPTImageSizesTypeScript(service.ExportGPTImageStudioSizeChips())

	if path := strings.TrimSpace(*checkPath); path != "" {
		current, err := os.ReadFile(path)
		if err != nil {
			fatal("read %s: %v", path, err)
		}
		if !bytes.Equal(current, payload) {
			fatal("artifact drift: run go run ./cmd/gpt-image-sizes-ssot --output %s", path)
		}
		return
	}
	if path := strings.TrimSpace(*outputPath); path != "" {
		if err := writeAtomic(path, payload); err != nil {
			fatal("write %s: %v", path, err)
		}
		return
	}
	if _, err := os.Stdout.Write(payload); err != nil {
		fatal("write stdout: %v", err)
	}
}

func renderGPTImageSizesTypeScript(chips []service.GPTImageStudioSizeChip) []byte {
	var b strings.Builder
	_, _ = b.WriteString("// Code generated by go run ./cmd/gpt-image-sizes-ssot; DO NOT EDIT.\n")
	_, _ = b.WriteString("// Owner: backend/internal/service/openai_images_aspect_ratio_tk.go (openAIImagesKnownSizeTable).\n")
	_, _ = b.WriteString("\n")
	_, _ = b.WriteString("export const GPT_IMAGE_SIZES: { ratio: string; value: string }[] = [\n")
	for _, chip := range chips {
		_, _ = fmt.Fprintf(&b, "  { ratio: %q, value: %q },\n", chip.Ratio, chip.Value)
	}
	_, _ = b.WriteString("]\n")
	return []byte(b.String())
}

func writeAtomic(path string, payload []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	defer func() {
		_ = tmp.Close()
		_ = os.Remove(tmpPath)
	}()
	if err := tmp.Chmod(0o644); err != nil {
		return err
	}
	if _, err := tmp.Write(payload); err != nil {
		return err
	}
	if err := tmp.Sync(); err != nil {
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpPath, path)
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gpt-image-sizes-ssot: "+format+"\n", args...)
	os.Exit(1)
}
