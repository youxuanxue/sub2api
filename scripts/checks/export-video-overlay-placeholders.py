#!/usr/bin/env python3
"""Export admin UI video/image placeholders from tk_pricing_overlay.json (SSOT).

Writes frontend/src/constants/tkVideoOverlayPlaceholders.tk.ts for Grok group
pricing form hints. Run after overlay tier changes:

  python3 scripts/checks/export-video-overlay-placeholders.py
  python3 scripts/checks/export-video-overlay-placeholders.py --check
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent.parent
OVERLAY = REPO / "backend" / "internal" / "service" / "tk_pricing_overlay.json"
OUT = REPO / "frontend" / "src" / "constants" / "tkVideoOverlayPlaceholders.tk.ts"

HEADER = """/** Generated by scripts/checks/export-video-overlay-placeholders.py — do not edit. */
"""


def _tier_rate(entry: dict, resolution: str) -> float:
    for tier in entry.get("video_price_tiers") or []:
        if tier.get("resolution") == resolution:
            rate = tier.get("output_cost_per_second")
            if isinstance(rate, (int, float)) and rate > 0:
                return float(rate)
    raise KeyError(f"missing tier {resolution!r}")


def _fmt_usd(rate: float) -> str:
    # Admin placeholders are short hints; trim float noise without rounding away cents.
    text = f"{rate:.10g}"
    if "." not in text:
        return f"{text}.0"
    return text.rstrip("0").rstrip(".") if "." in text else text


def build_payload(data: dict) -> dict:
    grok_video = data["grok-imagine-video"]
    grok_video_15 = data["grok-imagine-video-1.5"]
    grok_image = data["grok-imagine-image"]
    per_image = grok_image.get("output_cost_per_image")
    if not isinstance(per_image, (int, float)) or per_image <= 0:
        raise ValueError("grok-imagine-image missing output_cost_per_image")

    v480 = _fmt_usd(_tier_rate(grok_video, "480p"))
    v720 = _fmt_usd(_tier_rate(grok_video, "720p"))
    v15_480 = _fmt_usd(_tier_rate(grok_video_15, "480p"))
    v15_720 = _fmt_usd(_tier_rate(grok_video_15, "720p"))
    v15_1080 = _fmt_usd(_tier_rate(grok_video_15, "1080p"))

    return {
        "grok_video_admin_placeholders": {
            "video_price_480p": v480,
            "video_price_720p": v720,
            # 1080p is grok-imagine-video-1.5 only (admin copy documents both models).
            "video_price_1080p": v15_1080,
        },
        "grok_image_admin_placeholders": {
            "image_price_1k": _fmt_usd(float(per_image)),
            "image_price_2k": _fmt_usd(float(per_image)),
            "image_price_4k": _fmt_usd(float(per_image)),
        },
        "grok_video_admin_description": {
            "zh": (
                "配置 Grok 视频生成的每秒单价（USD/秒），留空则使用默认每秒价"
                f"（grok-imagine-video：480p ${v480}/s、720p ${v720}/s；"
                f"video-1.5：480p ${v15_480}/s、720p ${v15_720}/s、1080p ${v15_1080}/s）"
            ),
            "en": (
                "Configure Grok video generation prices in USD per second of output video. "
                "Leave empty to use the default per-second rates "
                f"(grok-imagine-video: ${v480}/s 480p, ${v720}/s 720p; "
                f"video-1.5: ${v15_480}/s 480p, ${v15_720}/s 720p, ${v15_1080}/s 1080p)."
            ),
        },
    }


def render_ts(payload: dict) -> str:
    v = payload["grok_video_admin_placeholders"]
    i = payload["grok_image_admin_placeholders"]
    d = payload["grok_video_admin_description"]
    return (
        HEADER
        + "\nexport const TK_GROK_VIDEO_ADMIN_PLACEHOLDERS = {\n"
        + f'  video_price_480p: "{v["video_price_480p"]}",\n'
        + f'  video_price_720p: "{v["video_price_720p"]}",\n'
        + f'  video_price_1080p: "{v["video_price_1080p"]}",\n'
        + "} as const\n\n"
        + "export const TK_GROK_IMAGE_ADMIN_PLACEHOLDERS = {\n"
        + f'  image_price_1k: "{i["image_price_1k"]}",\n'
        + f'  image_price_2k: "{i["image_price_2k"]}",\n'
        + f'  image_price_4k: "{i["image_price_4k"]}",\n'
        + "} as const\n\n"
        + "export const TK_GROK_VIDEO_ADMIN_DESCRIPTION = {\n"
        + f"  zh: {json.dumps(d['zh'], ensure_ascii=False)},\n"
        + f"  en: {json.dumps(d['en'])},\n"
        + "} as const\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if generated file drifted")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args()

    data = json.loads(OVERLAY.read_text(encoding="utf-8"))
    for key in ("grok-imagine-video", "grok-imagine-video-1.5", "grok-imagine-image"):
        if key not in data:
            print(f"  FAIL: overlay missing {key!r}", file=sys.stderr)
            return 1

    rendered = render_ts(build_payload(data))
    if args.check:
        if not OUT.is_file():
            print(f"  FAIL: missing {OUT.relative_to(REPO)}", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != rendered:
            print(
                f"  FAIL: {OUT.relative_to(REPO)} drifted — run "
                "python3 scripts/checks/export-video-overlay-placeholders.py",
                file=sys.stderr,
            )
            return 1
        if not args.quiet:
            print(f"  ok: {OUT.relative_to(REPO)} in sync with overlay")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    if not args.quiet:
        print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
